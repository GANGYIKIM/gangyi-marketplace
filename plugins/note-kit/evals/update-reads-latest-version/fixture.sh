#!/bin/bash
# 기존 아이디어 문서(v1)를 작업 폴더에 만든다. --scaffold 옵션을 줄 때만 실행된다.
set -e
d="ideas/llm-wiki-기반-개인-위키"
mkdir -p "$d"
cat > "$d/llm-wiki-기반-개인-위키.md" << 'DOC'
# LLM-Wiki 기반 개인 위키

> 메모와 노션에 흩어진 공부 기록을 AI가 누적해 정리하는 마크다운 위키로 모으려는 계획

- 작성일: 2026-10-15
- 버전: v1

## 목차
1. 배경
2. 핵심 내용
3. 열린 질문

## 1. 배경
공부 기록이 메모 앱과 노션에 나뉘어 있어 서로 연결되지 않는다.

## 2. 핵심 내용
새 기록이 들어올 때마다 기존 위키 페이지에 덧붙고 연결된다.

## 3. 열린 질문
- 위키 페이지와 원본 기록을 어떻게 나눠 보관할까?
DOC
